#!/usr/bin/env python3
"""Validate data/places.json and regenerate data.js (what the pages load).

Usage:
  python3 scripts/build.py          validate, then write data.js
  python3 scripts/build.py --check  validate and fail if data.js is out of date

Exit code 1 on any error. Warnings are printed but don't fail.
"""
import json, math, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "places.json")
OUT = os.path.join(ROOT, "data.js")

PECKHAM = (51.4734, -0.0690)
RADIUS_KM = 8.05  # 5 miles
TYPES = {"playground", "park", "nature", "farm", "museum", "water", "landmark", "activity", "library"}
SCOPES = {"local", "far"}
SOURCES = {"council", "ours", "ai", "you"}
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
URL = re.compile(r"^https?://[^\s]+$")


def km(a, b):
    r = 6371.0
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * r * math.asin(math.sqrt(h))


def norm(name):
    s = name.lower().replace("&", "and")
    s = re.sub(r"\b(the|playground|play area|park|gardens?)\b", "", s)
    return re.sub(r"[^a-z0-9]", "", s)


def validate(data):
    errors, warnings = [], []
    places = data.get("places")
    if not isinstance(places, list):
        return ["places must be a list"], []
    ids = set()
    for i, p in enumerate(places):
        where = f"#{i} {p.get('name', '?')!r}"
        for f in ("id", "name", "lat", "lon", "type", "scope", "source"):
            if p.get(f) in (None, ""):
                errors.append(f"{where}: missing {f}")
        if p.get("id") in ids:
            errors.append(f"{where}: duplicate id {p.get('id')}")
        ids.add(p.get("id"))
        if p.get("type") not in TYPES:
            errors.append(f"{where}: type must be one of {sorted(TYPES)}")
        if p.get("scope") not in SCOPES:
            errors.append(f"{where}: scope must be local or far")
        if p.get("source") not in SOURCES:
            errors.append(f"{where}: source must be one of {sorted(SOURCES)}")
        try:
            lat, lon = float(p["lat"]), float(p["lon"])
        except (KeyError, TypeError, ValueError):
            errors.append(f"{where}: lat/lon must be numbers")
            continue
        if p.get("scope") == "local":
            d = km(PECKHAM, (lat, lon))
            if d > RADIUS_KM:
                errors.append(f"{where}: {d:.1f} km from Peckham, outside the 5-mile area (set scope 'far' for holiday places)")
        ages = p.get("ages")
        if ages is not None and not (isinstance(ages, list) and len(ages) == 2 and 0 <= ages[0] <= ages[1] <= 18):
            errors.append(f"{where}: ages must be [min, max] between 0 and 18")
        ai = p.get("ai")
        if ai is not None:
            if not isinstance(ai.get("score"), int) or not 1 <= ai["score"] <= 10:
                errors.append(f"{where}: ai.score must be a whole number 1-10")
            if not ai.get("summary") or len(ai["summary"]) > 420:
                errors.append(f"{where}: ai.summary is required and must be at most 420 characters")
            src = ai.get("sources") or []
            if len(src) < 2:
                errors.append(f"{where}: ai.sources needs at least 2 links")
            for s in src:
                if not URL.match(str(s.get("url", ""))):
                    errors.append(f"{where}: bad source url {s.get('url')!r}")
            if not DATE.match(str(ai.get("reviewedAt", ""))):
                errors.append(f"{where}: ai.reviewedAt must be YYYY-MM-DD")
            a2 = ai.get("ages")
            if a2 is not None and not (isinstance(a2, list) and len(a2) == 2 and 0 <= a2[0] <= a2[1] <= 18):
                errors.append(f"{where}: ai.ages must be [min, max] between 0 and 18")
    # duplicates: same normalised name close together
    for i, a in enumerate(places):
        for b in places[i + 1:]:
            try:
                d = km((a["lat"], a["lon"]), (b["lat"], b["lon"])) * 1000
            except Exception:
                continue
            if norm(a["name"]) and norm(a["name"]) == norm(b["name"]) and d < 400:
                errors.append(f"possible duplicate: {a['name']!r} and {b['name']!r} ({d:.0f} m apart)")
            elif d < 15 and a.get("scope") == "local":
                warnings.append(f"co-located: {a['name']!r} and {b['name']!r} ({d:.0f} m)")
    return errors, warnings


def render(data):
    places = data["places"]
    return ("/* Generated by scripts/build.py from data/places.json. Do not edit by hand. */\n"
            "window.PLACES = " + json.dumps(places, ensure_ascii=False, indent=1) + ";\n")


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    errors, warnings = validate(data)
    for w in warnings:
        print("warning:", w)
    for e in errors:
        print("ERROR:", e)
    if errors:
        print(f"{len(errors)} error(s); data.js not written.")
        sys.exit(1)
    text = render(data)
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("ERROR: data.js is out of date. Run: python3 scripts/build.py")
            sys.exit(1)
        print(f"OK: {len(data['places'])} places, data.js up to date.")
        return
    open(OUT, "w", encoding="utf-8").write(text)
    n_ai = sum(1 for p in data["places"] if p.get("ai"))
    print(f"OK: {len(data['places'])} places ({n_ai} with AI reviews). Wrote data.js.")


if __name__ == "__main__":
    main()
